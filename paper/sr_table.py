#!/usr/bin/env python3
"""
sr_table.py — radial order S_r of the homeotropic droplets for C = +0.3, -0.3, 0 (paper/runs/droplets) and for the
Lebwohl-Lasher potential with the same nematic coupling (pear/runs/ll, A = 1.0), all with homeotropic W = 1.5.

For each radius and temperature it prints the mean and the standard deviation over runs, and the largest difference
between the variants in units of the largest standard deviation. Output: figs/sr_table.txt and a LaTeX table in
figs/sr_table.tex.

  python3 sr_table.py [--T 0.75 0.5 0.1] [--ll /path/to/pear/runs/ll] [--droplets /path/to/paper/runs/droplets]
"""
import argparse
import glob
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SIZES = (21, 31, 41)
VARIANTS = [  # label, folder pattern (N is substituted)
    ("$C=+0.3$", os.path.join(HERE, "runs", "droplets", "N{N}", "C0.3")),
    ("$C=-0.3$", os.path.join(HERE, "runs", "droplets", "N{N}", "C-0.3")),
    ("$C=0$", os.path.join(HERE, "runs", "droplets", "N{N}", "C0.0")),
    ("LL", os.path.join(ROOT, "pear", "runs", "ll", "N{N}")),
]


def sr_at(path, T):
    vals = []
    for d in sorted(glob.glob(os.path.join(path, "seed*"))):
        f = os.path.join(d, "po.dat")
        if not (os.path.exists(f) and os.path.exists(os.path.join(d, "DONE"))):
            continue
        df = pd.read_csv(f, sep=r"\s+")
        col = "Sr_sph" if "Sr_sph" in df else next((c for c in df.columns if c.lower().startswith("sr")), None)
        tcol = df.columns[0]                                  # first column is the temperature
        row = df[(pd.to_numeric(df[tcol], errors="coerce") - T).abs() < 2e-3]
        if col is None or not len(row):
            if f not in WARNED:
                WARNED.add(f)
                print(f"  [!] {f}: columns {list(df.columns)}; T range {df[tcol].min()}..{df[tcol].max()}"
                      + ("" if col else "; no S_r column"))
            continue
        vals.append(float(row[col].iloc[0]))
    return vals


WARNED = set()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--T", type=float, nargs="+", default=[0.75, 0.5, 0.1])
    ap.add_argument("--ll", default=None,
                    help="folder with the LL runs, containing N21/, N31/, N41/ (default: ../pear/runs/ll)")
    ap.add_argument("--droplets", default=None,
                    help="folder with the article droplet runs, containing N21/C0.3/ etc. (default: runs/droplets next "
                         "to this script)")
    args = ap.parse_args()
    if args.droplets:
        base = os.path.abspath(args.droplets)
        for k, c in enumerate(("C0.3", "C-0.3", "C0.0")):
            VARIANTS[k] = (VARIANTS[k][0], os.path.join(base, "N{N}", c))
    if args.ll:
        VARIANTS[-1] = ("LL", os.path.join(os.path.abspath(args.ll), "N{N}"))
    os.makedirs(os.path.join(HERE, "figs"), exist_ok=True)
    print("folders searched (N=21):")
    for lab, pat in VARIANTS:
        p = pat.format(N=21)
        n = len(glob.glob(os.path.join(p, "seed*", "DONE")))
        print(f"  {lab:10s} {p}  -> {'exists' if os.path.isdir(p) else 'NOT FOUND'}, {n} finished runs")
    print()
    lines, tex = [], []
    for T in args.T:
        lines.append(f"T = {T:g}")
        for N in SIZES:
            R = N / 2 - 1
            cells, means, sds = [], [], []
            for lab, pat in VARIANTS:
                v = sr_at(pat.format(N=N), T)
                if v:
                    m, s = float(np.mean(v)), float(np.std(v, ddof=1)) if len(v) > 1 else float("nan")
                    means.append(m)
                    sds.append(s)
                    cells.append(f"{lab}: {m:.3f} +- {s:.3f} (n={len(v)})")
                    tex_cell = f"${m:.3f}\\pm{s:.3f}$"
                else:
                    cells.append(f"{lab}: missing")
                    tex_cell = "--"
                if lab == VARIANTS[0][0]:
                    row = [f"{T:g}", f"{R:g}"]
                row.append(tex_cell)
            spread = max(means) - min(means) if len(means) > 1 else float("nan")
            big = np.nanmax(sds) if sds else float("nan")
            lines.append(f"  R={R:g}: " + "; ".join(cells) +
                         f"  | max difference {spread:.3f} = {spread / big:.1f} x largest sd")
            tex.append(" & ".join(row) + r" \\")
    txt = "\n".join(lines)
    print(txt)
    with open(os.path.join(HERE, "figs", "sr_table.txt"), "w") as f:
        f.write(txt + "\n")
    with open(os.path.join(HERE, "figs", "sr_table.tex"), "w") as f:
        f.write("% generated by sr_table.py\n$T$ & $R$ & " + " & ".join(v[0] for v in VARIANTS) + r" \\" + "\n")
        f.write("\n".join(tex) + "\n")


if __name__ == "__main__":
    main()
